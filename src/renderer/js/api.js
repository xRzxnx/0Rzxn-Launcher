// Accès au processus principal (exposé par preload.js) avec des messages d'erreur lisibles.
const bridge = window.launcher;

function clean(error) {
  const message = String(error?.message ?? error).replace(/^Error invoking remote method '[^']+': (\w*Error: )?/, '');
  return new Error(message);
}

function wrap(fn) {
  return async (...args) => {
    try {
      return await fn(...args);
    } catch (error) {
      throw clean(error);
    }
  };
}

